// Precomputes the blood-volume calibration (volumeOffsetFor) for the default build of each patient kind, so a page does not pay
// about two seconds for it at load. Run after any change to the physics or its constants (tests/calibrationBake.test.ts fails until you do):
//   npx tsx scripts/bake-calibration.ts
// Never edit src/physics/calibration.baked.ts by hand.
import { writeFileSync } from "node:fs";
import { BAKE_SETS, bakedKey, calibrateVolume } from "../src/physics/structural";

const lines: string[] = [];
for (const s of BAKE_SETS) {
  const key = bakedKey(s.spec, s.core, s.build), x = calibrateVolume(s.spec, s.core, s.build);
  lines.push(`  ${JSON.stringify(key)}: ${x},`);
  console.log(`${key}  ${x}`);
}
writeFileSync("src/physics/calibration.baked.ts", `// Generated by scripts/bake-calibration.ts: do not edit by hand.\n// Blood volume (ml) that puts each baseline's mean aortic pressure on its target, keyed by patient kind and a hash of everything the calibration depends on (bakedKey).\nexport const BAKED_OFFSETS: Record<string, number> = {\n${lines.join("\n")}\n};\n`);
console.log(`wrote src/physics/calibration.baked.ts (${lines.length} entries)`);
