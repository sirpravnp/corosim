import { it, vi } from "vitest";
import { Simulation } from "../src/sim/simulation";
import { TOOLS } from "../src/mcp/tools";
vi.setConfig({ testTimeout: 300_000 });
const run = (sim: Simulation, name: string, args: Record<string, unknown> = {}) => (TOOLS.find((x) => x.name === name)!.run({ sim, appUrl: "https://x/sim/" }, args) as any);
it("scratch", () => {
  const sim = new Simulation({ seed: 1 });
  const log = (t: string, r: any) => console.log(t, "=>", r.narrative);
  log("set", run(sim, "corosim_set_scenario", { engine: "core", scenario: { lesions: [{ artery: "LAD", occluded: true, position: 0.1 }] }, warmupSeconds: 20 }));
  log("adjust", run(sim, "corosim_adjust", { patch: { support: { norepinephrine: 0.4 }, bloodLoss: 0.2 }, runSeconds: 20 }));
  log("run", run(sim, "corosim_run", { seconds: 30 }));
  log("vt", run(sim, "corosim_adjust", { patch: { patient: { rhythm: "vt-mono" } }, runSeconds: 10 }));
  log("vf", run(sim, "corosim_adjust", { patch: { patient: { rhythm: "vf-coarse" } }, runSeconds: 10 }));
  log("treat", run(sim, "corosim_treat", { procedure: "pci", runSecondsAfter: 5 }));
  log("describe", run(sim, "corosim_describe_case"));
  log("set2", run(sim, "corosim_set_scenario", { engine: "core", scenario: { heart: { valves: { av: { open: 0.2, reg: 0 }, mv: { prosthesis: { kind: "mechanical", sizeMm: 29 } } } }, pericardium: { effusionMl: 400 }, electrolytes: { potassium: 2.8 }, devices: { impella: { level: 6 } } }, warmupSeconds: 10 }));
  log("valve", run(sim, "corosim_valve", { type: "tavr", sizeMm: 26, runSeconds: 5 }));
  const leg = new Simulation({ seed: 1 });
  log("legacy", run(leg, "corosim_set_scenario", { scenario: { lesions: [{ artery: "RCA", stenosis: 0.8 }] }, warmupSeconds: 10 }));
});
